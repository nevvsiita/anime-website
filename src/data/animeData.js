export const getLocalizedAnime = (anime, lang = 'es') => {
  if (!anime) return null;
  const langKey = lang || 'es';
  const title = (anime.titleByLang?.[langKey] || anime.titleByLang?.es || anime.title || '').toString();
  const synopsis = (anime.synopsisByLang?.[langKey] || anime.synopsisByLang?.es || anime.synopsis || '').toString();
  return {
    ...anime,
    title,
    synopsis,
    genres: Array.isArray(anime.genres) ? anime.genres : []
  };
};
